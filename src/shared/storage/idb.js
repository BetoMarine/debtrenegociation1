const DB_VERSION = 1;

export function openNamedDb(name) {
  return new Promise((resolve, reject) => {
    const req = indexedDB.open(name, DB_VERSION);
    req.onupgradeneeded = () => {
      const db = req.result;
      if (!db.objectStoreNames.contains("kv")) db.createObjectStore("kv");
      if (!db.objectStoreNames.contains("attachments")) db.createObjectStore("attachments");
      if (!db.objectStoreNames.contains("events")) db.createObjectStore("events", { autoIncrement: true });
    };
    req.onsuccess = () => resolve(req.result);
    req.onerror = () => reject(req.error);
  });
}

export function txDone(tx) {
  return new Promise((resolve, reject) => {
    tx.oncomplete = () => resolve();
    tx.onerror = () => reject(tx.error);
    tx.onabort = () => reject(tx.error || new Error("aborted"));
  });
}

export function requestResult(req) {
  return new Promise((resolve, reject) => {
    req.onsuccess = () => resolve(req.result);
    req.onerror = () => reject(req.error);
  });
}

export function cursorEach(store, range, visit) {
  return new Promise((resolve, reject) => {
    const req = range ? store.openCursor(range) : store.openCursor();
    req.onerror = () => reject(req.error);
    req.onsuccess = () => {
      const cursor = req.result;
      if (!cursor) {
        resolve();
        return;
      }
      visit(cursor);
      cursor.continue();
    };
  });
}

export function prefixRange(prefix) {
  return IDBKeyRange.bound(prefix, `${prefix}\uffff`);
}
